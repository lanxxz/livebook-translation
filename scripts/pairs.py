# -*- coding: utf-8 -*-
"""把版面块导出成「块号 + 原文」对照表 —— 骨架流水线翻译时的唯一依据。

为什么不直接用 _skel.txt：骨架里夹着说明注释和 %%EN/%%ZH 分隔符，
一眼看过去容易数错块。这个脚本只留块号和原文，照左边抄块号就不会错。

用法：
  python pairs.py <doc>              # 打印到终端
  python pairs.py <doc> out.txt      # 写文件（推荐，方便对照着写 _zh.txt）

输出示例：
  @@B 0  [chapter_open p23]
  TITLE: Big picture: What are LLMs?
  NUM: 1
  TOC: What Generative Pretrained Transformers
  INTRO: The hype around terms such as ...

  @@B 6  [figure p24]  key=p24_f0
  CAP: Figure 1.1 A simple haiku generated by ChatGPT

  @@B 20  [code p43]
  TITLE: Listing 2.1 ...
    |Vocab = {"a","b",...,"z"}
    NOTE-EN: this line is new
    (只写 @NOTE 行给注释中文，其它留空)
"""
import json
import os
import sys

for _s in (sys.stdout, sys.stderr):
    try:
        _s.reconfigure(encoding='utf-8', errors='replace')
    except Exception:
        pass


def project_root():
    def _up(start):
        d = os.path.abspath(start)
        for _ in range(4):
            if (os.path.exists(os.path.join(d, 'book.json'))
                    or os.path.exists(os.path.join(d, 'docs.json'))):
                return d
            d = os.path.dirname(d)
        return None

    for start in (os.path.dirname(os.path.abspath(__file__)), os.getcwd()):
        hit = _up(start)
        if hit:
            return hit
    return os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


ROOT = project_root()
WORK = os.path.join(ROOT, 'work')


def emit(doc):
    lay = json.load(open(os.path.join(WORK, doc + '_layout.json'),
                         encoding='utf-8'))['pages']
    out, idx, figc = [], 0, {}
    for pno in sorted(lay, key=int):
        for b in lay[pno]:
            t = b['type']
            head = '@@B %d  [%s p%s]' % (idx, t, pno)
            if t in ('figure', 'table'):
                fi = figc.get(pno, 0)
                figc[pno] = fi + 1
                head += '  key=p%s_f%d' % (pno, fi)
            out.append(head)
            if t == 'chapter_open':
                out.append('TITLE: ' + b.get('title', ''))
                out.append('NUM: ' + b.get('num', ''))
                for it in b.get('toc_items') or []:
                    out.append('TOC: ' + it)
                if b.get('intro'):
                    out.append('INTRO: ' + b['intro'])
            elif t in ('heading', 'para'):
                out.append(b.get('text', ''))
            elif t == 'note':
                out.append('LABEL: ' + b.get('label', 'NOTE'))
                out.append(b.get('text', ''))
            elif t in ('list', 'numlist'):
                for it in b.get('items') or []:
                    out.append('- ' + it)
            elif t == 'code':
                if b.get('title'):
                    out.append('TITLE: ' + b['title'])
                for ln in (b.get('text') or '').split('\n'):
                    out.append('  |' + ln)
                for n in (b.get('notes') or []):
                    out.append('  NOTE-EN: ' + n[0])
                out.append('  (只写 @NOTE 行给注释中文，其它留空)')
            elif t == 'figure':
                out.append('CAP: ' + (b.get('caption') or ''))
            elif t == 'table':
                g = b.get('grid') or {}
                data = g.get('data') or []
                out.append('CAP: ' + (b.get('caption') or ''))
                if data:
                    out.append('HDR: ' + ' | '.join(data[0]))
                    for row in data[1:]:
                        out.append('ROW: ' + ' | '.join(row))
            out.append('')
            idx += 1
    return '\n'.join(out)


def all_docs():
    p = os.path.join(ROOT, 'docs.json')
    if os.path.exists(p):
        return [d['id'] for d in json.load(open(p, encoding='utf-8'))]
    return []


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    if sys.argv[1] == '--all':
        for doc in all_docs():
            txt = emit(doc)
            p = os.path.join(WORK, doc + '_pairs.txt')
            open(p, 'w', encoding='utf-8').write(txt)
            print('%-8s %d bytes -> %s' % (doc, len(txt), p))
        return
    doc = sys.argv[1]
    txt = emit(doc)
    if len(sys.argv) > 2:
        open(sys.argv[2], 'w', encoding='utf-8').write(txt)
        print('written', sys.argv[2], len(txt), 'bytes')
    else:
        print(txt)


if __name__ == '__main__':
    main()
